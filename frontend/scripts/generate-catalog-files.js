/**
 * Script to generate `frontend/lib/pdf-catalog-data.ts`
 * and export unified data for mock-data.ts and admin-service.ts
 */

const fs = require('fs');
const path = require('path');
const cats = require('./catalog-categories.js');
const c1 = require('./items-cat-01-10.js');
const c2 = require('./items-cat-11-20.js');
const c3 = require('./items-cat-21-30.js');
const c4 = require('./items-cat-31-40.js');
const c5 = require('./items-cat-41-51.js');
const helpers = require('./catalog-helpers.js');

const allCategoryItems = [...c1, ...c2, ...c3, ...c4, ...c5];

// Map category icons
const iconMap = {
  1: 'Activity', 2: 'Layers', 3: 'Zap', 4: 'Sparkles', 5: 'Cpu',
  6: 'Maximize2', 7: 'Flame', 8: 'Gauge', 9: 'Radio', 10: 'Binary',
  11: 'CircuitBoard', 12: 'RotateCw', 13: 'Cpu', 14: 'Grid', 15: 'Thermometer',
  16: 'Compass', 17: 'Ruler', 18: 'Crosshair', 19: 'Wind', 20: 'Sun',
  21: 'Activity', 22: 'Globe', 23: 'Monitor', 24: 'Wifi', 25: 'Zap',
  26: 'ToggleLeft', 27: 'BatteryCharging', 28: 'Battery', 29: 'Cpu', 30: 'Share2',
  31: 'Wrench', 32: 'Tool', 33: 'Package', 34: 'Sliders', 35: 'Shield',
  36: 'Server', 37: 'Antenna', 38: 'Search', 39: 'Play', 40: 'Zap',
  41: 'Box', 42: 'HardDrive', 43: 'Truck', 44: 'BookOpen', 45: 'Link2',
  46: 'BatteryFull', 47: 'CheckCircle', 48: 'Volume2', 49: 'RefreshCw', 50: 'Archive',
  51: 'FileText'
};

const fullCategories = cats.map((cat, idx) => {
  return {
    id: `cat-${cat.slug}`,
    name: cat.name,
    slug: cat.slug,
    description: `Official ${cat.name} component collection from Hi Technology component catalog.`,
    icon_name: iconMap[cat.no] || 'Cpu',
    is_featured: idx < 12,
    sort_order: cat.no,
    product_count: cat.listed,
    highlighted_count: cat.highlighted
  };
});

const fullProducts = [];
const slugCounts = {};

for (const catGroup of allCategoryItems) {
  const meta = cats.find(x => x.no === catGroup.no);
  const catSlug = meta.slug;
  const catId = `cat-${catSlug}`;

  catGroup.items.forEach((item, itemIdx) => {
    const itemNo = itemIdx + 1;
    let baseSlug = helpers.generateSlug(item.name);
    if (!baseSlug) baseSlug = `item-${meta.no}-${itemNo}`;
    
    // Ensure unique slug
    if (slugCounts[baseSlug]) {
      slugCounts[baseSlug]++;
      baseSlug = `${baseSlug}-${slugCounts[baseSlug]}`;
    } else {
      slugCounts[baseSlug] = 1;
    }

    const price = helpers.getPriceForProduct(item.name, meta.no);
    const compareAt = Math.round(price * 1.25);
    const stock = item.h ? Math.floor(25 + ((itemNo * 7) % 65)) : 0;
    const is_in_stock = stock > 0;
    const sku = `HIT-${meta.no.toString().padStart(2, '0')}-${itemNo.toString().padStart(3, '0')}`;
    const primaryImg = helpers.getComponentImage(item.name, meta.name);
    const specs = helpers.extractSpecs(item.name, meta.name);

    fullProducts.push({
      id: `prod-${meta.no}-${itemNo}`,
      name: item.name,
      slug: baseSlug,
      sku: sku,
      category_id: catId,
      category_name: meta.name,
      brand_id: 'brand-generic',
      brand_name: 'Hi Technology',
      price: price,
      compare_at_price: compareAt,
      stock: stock,
      is_in_stock: is_in_stock,
      low_stock_threshold: 10,
      is_published: true,
      is_featured: item.h && (itemNo % 5 === 0),
      is_bestseller: item.h && (itemNo % 4 === 0),
      is_new_arrival: itemNo % 10 === 0,
      rating: 4.5 + ((itemNo % 5) * 0.1),
      review_count: 5 + ((itemNo * 3) % 45),
      short_description: `${item.name} - ${meta.name}`,
      description: `High-grade ${item.name} selected for professional engineering, robotics prototyping, and laboratory electronics projects. Sourced from authentic industrial electronics distributors with guaranteed specifications.`,
      primary_image: primaryImg,
      images: [primaryImg],
      specifications: specs,
      features: [
        'High quality and industrial reliability',
        'Standard breadboard/PCB mounting footprint',
        'Factory tested and verified',
        'Compliant with electronic safety standards'
      ],
      whats_included: [`1x ${item.name}`],
      compatibility: ['Arduino', 'Raspberry Pi', 'ESP32', 'Breadboard & Perfboard'],
      tags: [catSlug, 'electronics', 'components', item.h ? 'in-stock' : 'order-request']
    });
  });
}

console.log('Generated Categories:', fullCategories.length);
console.log('Generated Products:', fullProducts.length);
console.log('In-Stock Products:', fullProducts.filter(p => p.stock > 0).length);
console.log('Out-of-Stock Products:', fullProducts.filter(p => p.stock === 0).length);

// Write to json and ts
const outputPathTs = path.join(__dirname, '..', 'lib', 'pdf-catalog-data.ts');
const tsContent = `// AUTOGENERATED FROM "Hi Technology Electronics Shop - Component List" (PDF primary source of truth)
// 51 Categories | 1,187 Products | 520 Highlighted In-Stock | 667 Out-of-Stock

export interface PdfCategory {
  id: string;
  name: string;
  slug: string;
  description: string;
  icon_name: string;
  is_featured: boolean;
  sort_order: number;
  product_count: number;
  highlighted_count: number;
}

export interface PdfProduct {
  id: string;
  name: string;
  slug: string;
  sku: string;
  category_id: string;
  category_name: string;
  brand_id: string;
  brand_name: string;
  price: number;
  compare_at_price: number;
  stock: number;
  is_in_stock: boolean;
  low_stock_threshold: number;
  is_published: boolean;
  is_featured: boolean;
  is_bestseller: boolean;
  is_new_arrival: boolean;
  rating: number;
  review_count: number;
  short_description: string;
  description: string;
  primary_image: string;
  images: string[];
  specifications: Record<string, string>;
  features: string[];
  whats_included: string[];
  compatibility: string[];
  tags: string[];
}

export const pdfCategories: PdfCategory[] = ${JSON.stringify(fullCategories, null, 2)};

export const pdfProducts: PdfProduct[] = ${JSON.stringify(fullProducts, null, 2)};
`;

fs.writeFileSync(outputPathTs, tsContent, 'utf8');
console.log('Wrote file successfully to:', outputPathTs);
